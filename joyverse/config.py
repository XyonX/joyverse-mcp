# FILE STORAGE LIMITS
# ==========================================
# Pooled across every client: there is no per-client cap, so one client
# producing gigabytes does not starve the others.
STORAGE_ROOT = "storage"


def _env_int(name: str, default: int) -> int:
    """Read a byte-count limit from the environment."""
    raw = os.getenv(name, "").strip()
    if not raw:
        return default
    try:
        value = int(raw)
    except ValueError:
        return default
    return value if value > 0 else default


MB = 1024 * 1024
GB = 1024 * MB

# Per-file ceiling. Nothing can currently reach this: the only upload paths are
# save_file_from_url and save_file_base64, which is capped by MAX_INLINE_BYTES.
# It is left generous because the binding constraint is the per-user quota
# below, not any single object.
MAX_FILE_BYTES = _env_int("JOYVERSE_MAX_FILE_MB", 2048) * MB
MAX_USER_BYTES = _env_int("JOYVERSE_MAX_USER_GB", 50) * GB

# Largest file save_file_base64 will accept in one call. Base64 inflates by a
# third and the payload is charged to the agent's context window, so this stays
# small on purpose. Larger files need a transport that does not route bytes
# through the model, which does not exist yet.
MAX_INLINE_BYTES = _env_int("JOYVERSE_MAX_INLINE_MB", 8) * MB

# Guards for server-side URL fetches.
FETCH_TIMEOUT_SECONDS = _env_int("JOYVERSE_FETCH_TIMEOUT", 30)
MAX_REDIRECTS = 5

# Conversation logs are stored one object per day, named by date. Validated
# here because the date is user-supplied and becomes a key segment.
DATE_PATTERN = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def get_log_key(user_id: str, date: str) -> str:
    """R2 key for one day's conversation log.

    One object per day, rather than a single growing log, so that asking about
    a date reads one small object instead of scanning all history. The date is
    validated strictly before it becomes a path segment -- an unvalidated date
    is user input and this is a key.
    """
    if not DATE_PATTERN.match(date or ""):
        raise ValueError(f"Invalid date: {date!r}. Use YYYY-MM-DD.")
    return f"users/{_safe_user_id(user_id)}/logs/{date}.jsonl"
