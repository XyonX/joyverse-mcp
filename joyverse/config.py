# OAUTH CONFIGURATION
# ==========================================
# Loaded from the environment so no provider name or tenant is hardcoded in
# the application. The server stays usable with bearer auth alone when
# OAUTH_ENABLED is false, which is why nothing here raises at import time.

OAUTH_ENABLED = os.getenv("OAUTH_ENABLED", "false").strip().lower() in (
    "1", "true", "yes", "on"
)
AUTH0_DOMAIN = os.getenv("AUTH0_DOMAIN", "").strip()
AUTH0_AUDIENCE = os.getenv("AUTH0_AUDIENCE", "").strip()
AUTH0_CLIENT_ID = os.getenv("AUTH0_CLIENT_ID", "").strip()
PUBLIC_BASE_URL = os.getenv("PUBLIC_BASE_URL", "").strip().rstrip("/")

# Scopes this resource server understands. Advertised in the discovery
# document and enforced per tool in run.py.
READ_SCOPE = "joyverse:read"
WRITE_SCOPE = "joyverse:write"
SUPPORTED_SCOPES = [READ_SCOPE, WRITE_SCOPE]


def issuer_url() -> str:
    """The OAuth issuer, normalised with a trailing slash.

    Auth0's issuer is "https://tenant/" WITH the slash and PyJWT compares the
    claim as an exact string, so a missing slash would fail every token with a
    confusing "wrong issuer". Normalising here keeps that mistake out of the
    caller's hands.
    """
    if not AUTH0_DOMAIN:
        raise RuntimeError(
            "AUTH0_DOMAIN is not set. Add it to .env to enable OAuth.")
    domain = AUTH0_DOMAIN.rstrip("/")
    if not domain.startswith(("http://", "https://")):
        domain = f"https://{domain}"
    return f"{domain}/"


def authorization_servers() -> list:
    """Issuers listed in the RFC 9728 discovery document.

    The value MUST be byte-identical to the `issuer` field in the
    authorization server's own metadata, trailing slash included. A compliant
    MCP client fetches {AS}/.well-known/oauth-authorization-server and compares
    the two as strings; Auth0's issuer ends in "/", so stripping it here makes
    the client refuse to connect with:

        Authorization server metadata issuer mismatch:
        https://tenant.auth0.com/ != https://tenant.auth0.com

    That is why this returns issuer_url() unmodified while token validation
    uses the same string for PyJWT's exact `iss` match.
    """
    return [issuer_url()] if OAUTH_ENABLED and AUTH0_DOMAIN else []


def resource_url() -> str:
    """The canonical URL clients treat as this MCP resource."""
    if not PUBLIC_BASE_URL:
        raise RuntimeError(
            "PUBLIC_BASE_URL is not set. Add it to .env to advertise "
            "OAuth discovery metadata.")
    return f"{PUBLIC_BASE_URL}/mcp"

