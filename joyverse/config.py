# DYNAMIC KEY BUILDERS (Multi-user)
# ==========================================

def _safe_segment(value: str) -> str:
    """Rejects path-traversal attempts in a user-supplied key segment.

    Defence in depth. The primary guarantee is that user_id is server-minted
    and so can never contain a separator, but a user_id arriving from a token
    or a future caller must still be unable to escape its own prefix.
    """
    if "/" in value or "\\" in value or ".." in value or value.strip() == "":
        raise ValueError(f"Invalid key segment: {value!r}")
    return value


def _safe_user_id(value: str) -> str:
    """Validate a user_id before it becomes part of an R2 key.

    user_id is generated by identity.new_user_id(), so anything that does not
    match that exact shape did not come from us -- the registry namespace in
    particular must never be writable as if it were a user.
    """
    from joyverse.identity import is_user_id

    if not is_user_id(value):
        raise ValueError(f"Invalid user id: {value!r}")
    return value


def get_profile_key(user_id: str) -> str:
    return f"users/{_safe_user_id(user_id)}/profile.md"

def get_bio_key(user_id: str) -> str:
    return f"users/{_safe_user_id(user_id)}/bio.md"

def get_memory_key(user_id: str) -> str:
    return f"users/{_safe_user_id(user_id)}/memory.json"

def get_data_key(user_id: str, topic: str) -> str:
    # Use topic-specific filename based on known schemas
    filename_map = {
        "dsa": "progress.json",
        "projects": "active.json",
        "skills": "stack.json",
        "reading": "list.json",
        "games": "played.json",
    }
    filename = filename_map.get(topic, "progress.json")
    return f"users/{_safe_user_id(user_id)}/data/{_safe_segment(topic)}/{filename}"


